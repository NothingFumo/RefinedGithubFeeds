// 跟随 GitHub 界面语言：<html lang>。中文族归并到 zh，其余用 en 兜底。
function uiLocale() {
  const lang = document.documentElement.lang || '';
  if (/^zh/i.test(lang)) return 'zh';
  return 'en';
}

function t(key) {
  const loc = I18N[uiLocale()] || I18N.en;
  return loc[key] !== undefined ? loc[key] : (I18N.en[key] || key);
}
